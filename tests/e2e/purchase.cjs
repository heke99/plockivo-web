 await page.getByText('Varukorgen är sparad',{exact:true}).waitFor();
 await page.reload();
 await page.getByLabel('Kundreferens').waitFor();
 if(await page.getByLabel('Kundreferens').inputValue()!=='BROWSER-TEST')throw Error('cart reference lost on reload');
